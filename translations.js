// --- ГЕТТЕР ПЕРЕВОДОВ ---
window.getTranslation = function(key, params = {}) {
    let text = window.translations[currentLang]?.[key];
    if (typeof text === 'function') return text(params);

    if (typeof text === 'string' && text.includes('${')) {
        return text.replace(/\$\{(\w+)\}/g, (_, p) => params[p] || '');
    }
    return text || window.translations['ru'][key] || key;
};

// --- УСТАНОВКА ЯЗЫКА ---
window.setLanguage = function(lang) {
    currentLang = lang;
    localStorage.setItem('currentLang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const t = getTranslation(key);
        el.textContent = t;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const t = getTranslation(key);
        el.placeholder = t;
    });

    // обновляем кнопки выбора языка
    document.querySelectorAll('#language-selector .lang-btn')
        .forEach(btn => {
            btn.classList.toggle(
                'active',
                btn.textContent.toLowerCase() === lang
            );
        });
};
